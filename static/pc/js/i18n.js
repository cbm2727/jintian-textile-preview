(function () {
  var STORAGE_KEY = "site_lang";
  var DEFAULT_LANG = "en";

  function getLang() {
    try {
      return localStorage.getItem(STORAGE_KEY) || DEFAULT_LANG;
    } catch (e) {
      return DEFAULT_LANG;
    }
  }

  function setLang(lang) {
    try {
      localStorage.setItem(STORAGE_KEY, lang);
    } catch (e) {}
  }

  function applyLang(lang) {
    var dict = TRANSLATIONS[lang] || TRANSLATIONS[DEFAULT_LANG];
    var fallback = TRANSLATIONS[DEFAULT_LANG];
    var nodes = document.querySelectorAll("[data-i18n]");
    for (var i = 0; i < nodes.length; i++) {
      var key = nodes[i].getAttribute("data-i18n");
      var value = dict[key] !== undefined ? dict[key] : fallback[key];
      if (value !== undefined) {
        nodes[i].textContent = value;
      }
    }
    var placeholderNodes = document.querySelectorAll("[data-i18n-placeholder]");
    for (var j = 0; j < placeholderNodes.length; j++) {
      var pKey = placeholderNodes[j].getAttribute("data-i18n-placeholder");
      var pValue = dict[pKey] !== undefined ? dict[pKey] : fallback[pKey];
      if (pValue !== undefined) {
        placeholderNodes[j].setAttribute("placeholder", pValue);
      }
    }
    document.documentElement.setAttribute("lang", lang);
  }

  function init() {
    var lang = getLang();
    var select = document.getElementById("langSelect");
    if (select) {
      select.value = lang;
      select.addEventListener("change", function () {
        setLang(this.value);
        applyLang(this.value);
      });
    }
    applyLang(lang);
  }

  if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", init);
  } else {
    init();
  }
})();
